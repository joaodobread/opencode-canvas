export const EDITABLE_KINDS = ["screen", "component", "prototype", "document"] as const

export type EditOp =
  | { type: "text"; before: string; after: string; index?: number }
  | { type: "style"; selector: string; props: Record<string, string> }
  | { type: "reset"; selector: string }

export const STYLE_PROPS = [
  "color",
  "background-color",
  "font-size",
  "font-weight",
  "font-family",
  "text-align",
  "line-height",
  "letter-spacing",
  "padding-top",
  "padding-bottom",
  "padding-left",
  "padding-right",
  "margin-top",
  "margin-bottom",
  "border-radius",
  "opacity",
] as const

const BLOCK = /<style data-canvas-edits>([\s\S]*?)<\/style>\n?/i
const INLINE_TAGS = "b|i|strong|em|span|a|code|br|small|mark|u|s|sub|sup"

function fail(message: string): never {
  throw new Error(message)
}

function safeSelector(value: unknown): string {
  if (typeof value !== "string" || !value.trim() || value.length > 400) fail("Invalid selector.")
  if (/[{};<\n\r]|\/\*/.test(value)) fail("Invalid selector.")
  return value.trim()
}

function safeValue(prop: string, value: unknown): string {
  if (typeof value !== "string") fail(`"${prop}" must be a string.`)
  const trimmed = value.trim()
  if (trimmed.length > 160 || /[{};<>\\]|\/\*|url\s*\(|expression|@import/i.test(trimmed)) fail(`Invalid value for "${prop}".`)
  return trimmed
}

type Rules = Map<string, Map<string, string>>

function readRules(html: string): Rules {
  const rules: Rules = new Map()
  const body = BLOCK.exec(html)?.[1] ?? ""
  for (const line of body.split("\n")) {
    const match = /^(.+?)\{(.*)\}\s*$/.exec(line.trim())
    if (!match) continue
    const props = new Map<string, string>()
    for (const part of match[2]!.split(";")) {
      const at = part.indexOf(":")
      if (at > 0) props.set(part.slice(0, at).trim(), part.slice(at + 1).replace(/!important\s*$/i, "").trim())
    }
    rules.set(match[1]!.trim(), props)
  }
  return rules
}

function writeRules(html: string, rules: Rules): string {
  const lines = [...rules]
    .filter(([, props]) => props.size)
    .map(([selector, props]) => `${selector}{${[...props].map(([key, value]) => `${key}:${value}!important`).join(";")}}`)
  const stripped = html.replace(BLOCK, "")
  if (!lines.length) return stripped
  const block = `<style data-canvas-edits>\n${lines.join("\n")}\n</style>\n`
  const close = stripped.toLowerCase().lastIndexOf("</body>")
  return close >= 0 ? `${stripped.slice(0, close)}${block}${stripped.slice(close)}` : `${stripped.replace(/\s*$/, "\n")}${block}`
}

function applyStyle(html: string, selector: string, props: Record<string, string>): string {
  const rules = readRules(html)
  const rule = rules.get(selector) ?? new Map<string, string>()
  for (const [prop, raw] of Object.entries(props)) {
    if (!(STYLE_PROPS as readonly string[]).includes(prop)) fail(`Property "${prop}" cannot be edited.`)
    const value = safeValue(prop, raw)
    if (value) rule.set(prop, value)
    else rule.delete(prop)
  }
  if (rule.size) rules.set(selector, rule)
  else rules.delete(selector)
  return writeRules(html, rules)
}

function applyReset(html: string, selector: string): string {
  const rules = readRules(html)
  rules.delete(selector)
  return writeRules(html, rules)
}

function applyText(html: string, before: string, after: string, index: number): string {
  if (before === after) return html
  if (!before.trim()) fail("There is no text to replace.")
  const tags = (value: string) => value.match(/<\/?[a-z][^>]*>/gi) ?? []
  for (const tag of tags(after)) {
    if (!new RegExp(`^</?(${INLINE_TAGS})(\\s|/|>)`, "i").test(tag)) fail("Only plain text and simple inline formatting can be edited here.")
  }
  if (/\son\w+\s*=/i.test(after) && !/\son\w+\s*=/i.test(before)) fail("Event handlers cannot be added.")
  const body = /<body[^>]*>/i.exec(html)
  const from = body ? body.index + body[0].length : 0
  const needle = `>${before}<`
  const matches: number[] = []
  for (let at = html.indexOf(needle, from); at >= 0; at = html.indexOf(needle, at + 1)) matches.push(at)
  const position = matches[index]
  if (position === undefined) {
    fail("Could not find that text in the design source (it may be generated by a script). Leave a comment so the agent can change it.")
  }
  return `${html.slice(0, position + 1)}${after}${html.slice(position + 1 + before.length)}`
}

export function parseOps(value: unknown): EditOp[] {
  if (!Array.isArray(value) || !value.length || value.length > 40) fail("ops must be a non-empty list.")
  return value.map((raw): EditOp => {
    const op = raw as Record<string, unknown>
    if (op.type === "text") {
      if (typeof op.before !== "string" || typeof op.after !== "string") fail("Text edits need before and after.")
      const index = typeof op.index === "number" && Number.isInteger(op.index) && op.index >= 0 ? op.index : 0
      return { type: "text", before: op.before, after: op.after, index }
    }
    if (op.type === "style") {
      const props = op.props
      if (!props || typeof props !== "object" || Array.isArray(props)) fail("Style edits need props.")
      return { type: "style", selector: safeSelector(op.selector), props: props as Record<string, string> }
    }
    if (op.type === "reset") return { type: "reset", selector: safeSelector(op.selector) }
    return fail("Unknown edit type.")
  })
}

export function applyEdits(html: string, ops: EditOp[]): string {
  let out = html
  for (const op of ops) {
    if (op.type === "text") out = applyText(out, op.before, op.after, op.index ?? 0)
    else if (op.type === "style") out = applyStyle(out, op.selector, op.props)
    else out = applyReset(out, op.selector)
  }
  return out
}
